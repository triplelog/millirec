// Raw matcher result → calibrated {chars, probs}.
//
// The wasm returns [idx,cost, idx,cost, idx,cost] (top-3 class index + class
// score). Stroke mode keeps the historical cost softmax; image mode uses a
// logistic fit on the margin ratio, because the tuned image parameters
// produce class costs well above 1 where the softmax compresses every
// probability toward 1/3.
//
// CALIBRATION constants are fit by tuning/calibrate.cjs on held-out margins.
// Current fit (Jul 25 2026, margins-glyphs.json — REAL glyph photos from the
// training-glyphs zips + synthetic "smashed two-glyph" negatives, generated by
// tuning/glyph-margins.cjs; REFIT for the α=5 γ=3 κ0=0.02 rebalance):
//   p(correct) = σ(0.6884·ln(v2/v1) − 0.6846·ln(v1) + 1.0768)
// The negatives are what earn the strong −0.6846·ln(v1) term (was ≈0 when the
// fit only saw real MNIST digits): absolute match quality suppresses
// confident-but-wrong inputs. On the fit set, ≥0.9 accepts 442/1446 at 93.0%
// precision. NOTE the bias is NEGATIVE at these parameters (α=5 shifts costs
// up, so ln(v1) is larger and the intercept moves to compensate) — the applied
// form is σ(margin·ln(v2/v1) − mag·ln(v1) − bias), so a stored bias of
// −1.0768 adds +1.0768. REFIT whenever matcher parameters change and update
// this table only — every consumer reads it from here.
// (Pre-rebalance α=0.4 γ=2 constants were 1.3216/0.6076/1.9129; pre-glyph
// 2.6914/0.0686/0.0963 on margins-kappa-best; pre-curvature
// 1.3912/0.1396/0.9256 on margins-mnist-tuned.)

import { SECOND_AVERAGE } from './constants.js'

// `image` — shape-only photo confidence (no baseline geometry available).
// `imageGeom` — photo confidence AFTER geometry is fused into cost space
// (library/src/char.js geoFuse: adjustedCost = shapeCost + geoLambda·(−geometry
// logLik), re-ranked, then this logistic). Fusing geometry into the COST that
// the logistic reads — rather than a post-hoc softmax rerank — is what keeps
// the ln(v1) absolute-quality term alive: the old geoRerank softmax was
// shift-invariant and normalized the winner's absolute confidence away, so it
// showed ~99% on wrong/garbage blobs (≈66% precise at ≥0.99, 62% of smashed
// negatives ≥0.99). Fused + recalibrated (Jul 25 2026, margins-glyphs-geom.json,
// geoLambda=0.5, α=5 γ=3 κ0=0.02): σ(0.6925·ln(v2/v1) − 1.0731·ln(v1) + 2.4927)
// → ≥0.9 accepts 612/1446 at 96.9% precision. Shape-only top-1 on this pool is
// 90.7% at the rebalanced parameters (was 88.7% at α=0.4 γ=2). Refit with
// tuning/glyph-geo-eval.cjs (dumps the margins) + tuning/calibrate.cjs.
// (Pre-rebalance constants were 0.9294/1.5347/0.9152.)
export const CALIBRATION = {
  image: { margin: 0.6884, mag: 0.6846, bias: -1.0768 },
  imageGeom: { margin: 0.6925, mag: 1.0731, bias: -2.4927 },
}

/** p(this candidate is correct | its cost `a`, strongest rival's cost `b`)
 *  under the fitted logistic. For the winner b > a (positive margin ⇒ high);
 *  for a runner-up its rival is the winner, so b < a (negative margin ⇒ low).
 *  Applied per candidate this gives every slot the SAME confidence question the
 *  top-1 answers, and — because v1 < v2 < v3 — yields conf1 > conf2 > conf3. */
function calibratedProb(a, b, { margin, mag, bias }) {
  if (a < 1e-9) return 0.99
  return 1 / (1 + Math.exp(-(margin * Math.log(Math.max(b, 1e-9) / a) - mag * Math.log(a) - bias)))
}

/**
 * Convert a raw result array into {chars: [top3], probs: [top3]}.
 * `mode` picks the confidence model — any key in CALIBRATION ('image',
 * 'imageGeom') uses the logistic margin model; anything else (stroke) uses the
 * historical cost softmax. `secondAverage` is the stroke softmax floor term.
 */
export function parseResult(result, charList, mode, secondAverage = SECOND_AVERAGE) {
  const chars = []
  for (let i = 0; i < 3; i++) chars.push(charList[result[2 * i]])
  const cal = CALIBRATION[mode]
  if (cal) {
    // Every candidate answers the same question as #1: P(this char is correct)
    // vs its strongest rival (the cheapest of the OTHER costs). #1's rival is
    // #2 (unchanged top-1 number); #2 and #3's rival is #1, so they read low.
    const costs = [result[1], result[3], result[5]]
    const probs = costs.map((c, i) => {
      let rival = Infinity
      for (let j = 0; j < 3; j++) if (j !== i) rival = Math.min(rival, costs[j])
      return calibratedProb(c, rival, cal)
    })
    return { chars, probs }
  }
  const denom = Math.max(result[1], secondAverage / 1000)
  let totalProb = Math.exp((-1 * secondAverage) / denom)
  for (let i = 0; i < 3; i++) totalProb += Math.exp((-1 * result[2 * i + 1]) / denom)
  const probs = []
  for (let i = 0; i < 3; i++) {
    probs.push(Math.exp((-1 * result[2 * i + 1]) / denom) / totalProb)
  }
  return { chars, probs }
}
